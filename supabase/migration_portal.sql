-- OS digital GC — portal do dentista, tabelas de preço e arquivos.
-- Rode este script inteiro no SQL Editor do projeto da GC (pode rodar de novo sem problema).

-- 1) Tabelas de preço -------------------------------------------------------
create table if not exists tabelas_preco (
  id uuid primary key default gen_random_uuid(),
  nome text not null,
  criada_em timestamptz not null default now()
);

-- Um preço por serviço do catálogo (ex: "PSD – Coroa – Zircônia") em cada tabela.
create table if not exists precos (
  tabela_id uuid not null references tabelas_preco(id) on delete cascade,
  servico text not null,
  valor numeric(10,2) not null default 0,
  primary key (tabela_id, servico)
);

-- 2) Dentistas (um por conta de login) --------------------------------------
create table if not exists dentistas (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null default '',
  clinica text,
  whatsapp text,
  email text,
  tabela_id uuid references tabelas_preco(id) on delete set null,
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

-- Quando alguém cria a conta, já nasce o cadastro de dentista com os dados do formulário.
create or replace function public.criar_dentista()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.dentistas (id, nome, clinica, whatsapp, email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nome', ''),
    new.raw_user_meta_data->>'clinica',
    new.raw_user_meta_data->>'whatsapp',
    new.email
  )
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists ao_criar_usuario on auth.users;
create trigger ao_criar_usuario after insert on auth.users
  for each row execute function public.criar_dentista();

-- 3) Pedidos: dono, número da OS e valor ------------------------------------
alter table pedidos add column if not exists dentista_id uuid references dentistas(id) on delete set null;
alter table pedidos add column if not exists valor_estimado numeric(10,2);
alter table pedidos add column if not exists numero bigint generated by default as identity;
create index if not exists idx_pedidos_dentista on pedidos(dentista_id);

-- 4) Arquivos enviados (STL, fotos...) --------------------------------------
create table if not exists pedido_arquivos (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null references pedidos(id) on delete cascade,
  dentista_id uuid references dentistas(id) on delete set null,
  nome text not null,
  caminho text not null,          -- caminho no Storage (bucket "arquivos-os")
  tamanho bigint,
  drive_id text,                  -- id do arquivo copiado para o Google Drive
  drive_url text,
  removido_do_servidor boolean not null default false,
  criado_em timestamptz not null default now()
);
create index if not exists idx_pedido_arquivos_pedido on pedido_arquivos(pedido_id);

-- 5) Segurança (RLS): cada dentista só enxerga o que é dele -----------------
alter table tabelas_preco enable row level security;
alter table precos enable row level security;
alter table dentistas enable row level security;
alter table pedido_arquivos enable row level security;

drop policy if exists "dentista le o proprio cadastro" on dentistas;
create policy "dentista le o proprio cadastro" on dentistas
  for select to authenticated using (id = auth.uid());

drop policy if exists "dentista le a propria tabela" on tabelas_preco;
create policy "dentista le a propria tabela" on tabelas_preco
  for select to authenticated using (id = (select tabela_id from dentistas where id = auth.uid()));

drop policy if exists "dentista le os precos da propria tabela" on precos;
create policy "dentista le os precos da propria tabela" on precos
  for select to authenticated using (tabela_id = (select tabela_id from dentistas where id = auth.uid()));

drop policy if exists "dentista cria os proprios pedidos" on pedidos;
create policy "dentista cria os proprios pedidos" on pedidos
  for insert to authenticated with check (dentista_id = auth.uid());

drop policy if exists "dentista le os proprios pedidos" on pedidos;
create policy "dentista le os proprios pedidos" on pedidos
  for select to authenticated using (dentista_id = auth.uid());

drop policy if exists "dentista registra os proprios arquivos" on pedido_arquivos;
create policy "dentista registra os proprios arquivos" on pedido_arquivos
  for insert to authenticated with check (dentista_id = auth.uid());

drop policy if exists "dentista le os proprios arquivos" on pedido_arquivos;
create policy "dentista le os proprios arquivos" on pedido_arquivos
  for select to authenticated using (dentista_id = auth.uid());

-- 6) Storage: bucket privado para os arquivos dos casos ---------------------
insert into storage.buckets (id, name, public, file_size_limit)
values ('arquivos-os', 'arquivos-os', false, 52428800)  -- até 50 MB por arquivo (limite do plano grátis)
on conflict (id) do update set file_size_limit = excluded.file_size_limit;

drop policy if exists "dentista envia na propria pasta" on storage.objects;
create policy "dentista envia na propria pasta" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'arquivos-os' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "dentista le a propria pasta" on storage.objects;
create policy "dentista le a propria pasta" on storage.objects
  for select to authenticated
  using (bucket_id = 'arquivos-os' and (storage.foldername(name))[1] = auth.uid()::text);

-- 7) Uma tabela inicial para começar ----------------------------------------
insert into tabelas_preco (nome)
select 'Padrão' where not exists (select 1 from tabelas_preco);

notify pgrst, 'reload schema';
